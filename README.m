### Cheat mode (for reviewers)

Press **P** in game to turn cheat mode ON / OFF. The other keys work only while it is ON.

| Key | Effect |
|-----|--------|
| `P` | cheat mode ON / OFF (OFF also removes invincibility) |
| `A` | invincible ON / OFF (ghosts cannot kill Pac-Man) |
| `C` / `N` | skip the current level |
| `M` | +1 life |
| `W` | win the game (jump to the victory screen) |
| `L` | lose the game (jump to the game over screen) |

The HUD shows `CHEAT Mode : ON` and the list of keys while cheat mode is active.

