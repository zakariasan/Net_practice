## General Software Architecture

```
src/
├── __main__.py              entry: read argv, load Config, start Game
├── parser/
│   └── load_config.py       Config (pydantic model): defaults, validation, JSON + comments
├── logic/
│   ├── game.py              Game: window, main loop, events, states, levels, collisions, timer, cheats
│   ├── game_state.py        GameState: score, lives, level, timer, pacgums, cheat flags (shared)
│   ├── maze_env.py          MazeEnv: maze grid, drawing surface, cell size, config, current state (shared)
│   └── save_scores.py       save_score(): top-10 JSON file
└── graphic/
    ├── colors.py            color palette
    ├── maze_graphic.py      MazeGraphic: draws the walls
    ├── characters/
    │   ├── init.py          Direction, Corner enums
    │   ├── character.py     Character (abstract): cell-to-cell movement, wall checks, draw
    │   ├── pacman.py        Pacman(Character): start in the middle, eat pacgums
    │   └── ghost.py         Ghost(Character): modes, BFS, afraid / eaten
    │                         Blinky, Pinky, Inky, Clyde(Ghost): define_target()
    ├── pacgums/pacgum.py    Pacgum: normal or super, points, draw
    ├── menus/
    │   ├── menu_widget.py   MenuWidget: list of widgets, layout (font size from window), draw, clicks
    │   ├── main_menu.py     MainMenu(MenuWidget)
    │   ├── hud_menu.py      HudMenu(MenuWidget): score, lives, level, time, power, cheat keys
    │   └── pause_menu.py    PauseMenu(MenuWidget)
    ├── screens/             InstructionScreen, HighScoresScreen, WinnerScreen, LoserScreen (MenuWidget)
    └── widgets/             TextWidget, ButtonWidget, InputWidget
```

Relationships:
- `Game` owns the window, every screen, `Pacman` and the 4 ghosts, and switches screens with `MazeEnv.state`.
- `MazeEnv` and `GameState` are **shared class-level state**: characters, pacgums and screens read the maze,
  cell size and score from them instead of receiving them as parameters.
- `Character` → `Pacman`, `Ghost` → `Blinky / Pinky / Inky / Clyde` (inheritance; each ghost only overrides
  its target).
- Every screen is a `MenuWidget` holding a list of widgets; `calculate_layout()` sizes fonts from the window
  size, `draw()` stacks the widgets vertically and centers them.

