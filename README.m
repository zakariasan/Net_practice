# PAC-MAN — Ghosts! More ghosts!

## Description

A complete, playable Pac-Man game written in Python with an object-oriented, modular architecture.

- Mazes are generated by an **external A-Maze-ing package** (assigned by another group, used as-is),
  with `PERFECT = False` so corridors have loops like a real Pac-Man board.
- Every game parameter (lives, levels, points, maze size, timers…) comes from a **JSON config file**
  (with `#` comment lines).
- 4 ghosts with their own personality chase Pac-Man using a **BFS path search** through the corridors.
- **Highscores** (top 10) are saved on disk and shown from the main menu.
- A **cheat mode** helps reviewers reach every screen quickly.

Game loop: **Main menu → Start → play levels → Win or Lose → enter your name → Main menu**.

