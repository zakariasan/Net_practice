## Implementation

### Game loop and states

`Game.run()` runs at 60 FPS and draws one screen depending on `MazeEnv.state`:

```
MENU ──Start──▶ PLAYING ──ESC/SPACE──▶ PAUSE ──Resume──▶ PLAYING
                   │                     └──Main menu──▶ MENU
                   ├── all levels done ──▶ WINNER ──name + Enter──▶ MENU
                   └── lives = 0 ─────────▶ LOSER  ──name + Enter──▶ MENU
MENU ──Highscores / Instructions──▶ screen ──ESC / BACK──▶ MENU
MENU ──Exit──▶ quit
```

One frame in `PLAYING`:
1. read keys → 2. move Pac-Man → 3. eat pacgum (score, super pacgum = ghosts blue)
→ 4. if no pacgum left → next level / victory, else move ghosts, check collisions, update timer
→ 5. update HUD → 6. draw maze, pacgums, ghosts, Pac-Man.

### Rules

- Small pacgum `+points_per_pacgum`; super pacgum (4 corners) `+points_per_super_pacgum` and all ghosts turn
  blue for `afraid_time` seconds (they blink white during the last 2 s, the HUD shows the time left).
- Blue ghost touched → `+points_per_ghost`, the ghost disappears and comes back to its corner after
  `ghost_pwn_time` seconds (only when Pac-Man is not standing next to that corner).
- Normal ghost touched → lose 1 life, Pac-Man back to the middle, ghosts back to their corners.
- Timer reaches 0 → lose 1 life, timer restarts.
- Score and lives are kept between levels; the score never decreases.

### Movement

Characters move cell to cell: a move is chosen only when the character is exactly on a cell, then it slides
toward the next cell (`speed` = fraction of a cell per frame: Pac-Man `0.1`, ghosts `0.05`, blue ghosts `0.03`).
A direction is allowed when the current cell has no wall bit on that side.

### Ghost AI

Each ghost picks a **target cell**, then a **BFS** decides the next move:

| Ghost | Color | Chase target |
|-------|-------|--------------|
| Blinky | red | Pac-Man's cell |
| Pinky | pink | 4 cells in front of Pac-Man |
| Inky | cyan | 2 cells in front of Pac-Man |
| Clyde | orange | Pac-Man when far (> 8 cells), his own corner when close |

- Modes: **chase** 20 s ↔ **scatter** 5 s (target = own corner); **afraid** after a super pacgum (run away,
  slower, reverses direction once).
- Target outside the maze → clamped to the border; target on a closed cell → Pac-Man's cell.
- BFS (`Ghost.bfs_steps`): fill a grid of the maze size with `-1`, set the target to `0`, then walk a list of
  cells — every open neighbor still at `-1` gets "my value + 1". At the end each cell holds its number of steps
  to the target **through the corridors**.
- At each cell the ghost looks at its open neighbors (no U-turn) and takes the **smallest** number;
  when afraid it takes the **biggest** (runs away).

