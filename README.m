## Highscore

- Stored in a JSON file on disk: a list of `{"name": str, "score": int}` objects.
- Only the **top 10** scores are kept, sorted from highest to lowest.
- At the end of a game (victory or game over), the player types a name
  (**max 10 characters, letters, digits and spaces only**) and presses Enter.
- The list is shown from the main menu → **Highscores**.

Why JSON: human-readable, no extra dependency, easy to check and reset during a review.
A missing or broken file must never crash the game: it is treated as an empty list.

