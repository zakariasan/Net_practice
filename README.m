## Maze Generation

The maze comes from the assigned **A-Maze-ing** package (`mazegenerator`, installed from the wheel at the
repo root, never modified):

```python
from mazegenerator import MazeGenerator

maze = MazeGenerator(size=(width, height), seed=seed, perfect=False).maze
```

- `perfect=False` → the generator adds loops, so ghosts and Pac-Man have several ways around.
- The result is a 2D list of integers. Each cell stores its walls as bits:

  | Bit | Wall |
  |-----|------|
  | `1` | North (up) |
  | `2` | East (right) |
  | `4` | South (down) |
  | `8` | West (left) |

  A cell equal to `15` is closed on all sides (the generator's "42" pattern) — nothing is placed there.
- Level 1 uses the config `seed`; every next level uses a new random seed.
- If the generator raises an error, it is caught and reported (`Game.new_maze`) instead of crashing.

