## Configuration

JSON file. Lines starting with `#` (or `//`) are comments and are ignored.

```json
# Pac-Man configuration
{
  "highscore_filename": "scores",
  "levels": 10,
  "width": 20,
  "height": 20,
  "lives": 3,
  "pacgum": 42,
  "points_per_pacgum": 10,
  "points_per_super_pacgum": 50,
  "points_per_ghost": 200,
  "seed": 42,
  "level_max_time": 90,
  "afraid_time": 7,
  "ghost_pwn_time": 5
}
```

| Key | Default | Meaning |
|-----|---------|---------|
| `highscore_filename` | `"scores"` | file where highscores are stored |
| `levels` | `10` | number of levels to win the game |
| `width`, `height` | `20`, `20` | maze size in cells (minimum 5) |
| `lives` | `3` | lives at the start of a game |
| `pacgum` | `42` | number of small pacgums placed per level (clamped to the free cells) |
| `points_per_pacgum` | `10` | points for a pacgum |
| `points_per_super_pacgum` | `50` | points for a super pacgum (4 corners) |
| `points_per_ghost` | `200` | points for eating a blue ghost |
| `seed` | `42` | seed of the **first** level's maze; next levels use random seeds |
| `level_max_time` | `90` | seconds per level; time out = lose 1 life, timer restarts |
| `afraid_time` | `7` | seconds the ghosts stay blue after a super pacgum |
| `ghost_pwn_time` | `5` | seconds before an eaten ghost comes back to its corner |

Every key is optional: a missing key takes its default value.
Faulty values must be replaced by their default with a clear message, and unknown keys ignored
(subject V.3).

